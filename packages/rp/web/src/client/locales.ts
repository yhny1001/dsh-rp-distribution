/**
 * Localize first-party Experiences while preserving third-party package names.
 *
 * @param id Experience identifier.
 * @param fallback Display name supplied by the capability catalog.
 * @param t Locale lookup function.
 * @returns The localized first-party name or the supplied fallback.
 */
export function experienceLabel(
  id: string,
  fallback: string,
  t: (key: RpStudioLocaleKey) => string,
): string {
  const key = EXPERIENCE_LOCALE_KEYS[id]
  return key === undefined ? fallback : t(key)
}
